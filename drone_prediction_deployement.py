# -*- coding: utf-8 -*-

import streamlit as st
import pandas as pd
import joblib


# --------------------------------------------------
# Load Model and Label Encoder
# --------------------------------------------------

model = joblib.load("drone_type_model.pkl")
label_encoder = joblib.load("drone_type_label_encoder.pkl")


# --------------------------------------------------
# Page Configuration
# --------------------------------------------------

st.set_page_config(
    page_title="Drone Type Prediction",
    page_icon="🚁",
    layout="centered"
)


# --------------------------------------------------
# Title
# --------------------------------------------------

st.title("🚁 Drone Type Prediction System")

st.write(
    "Enter the drone details below to predict "
    "whether it is a Mini Drone or Professional Drone."
)


# --------------------------------------------------
# User Input
# --------------------------------------------------

Name = st.text_input(
    "Drone Name",
    "My Drone"
)

Control_Range = st.number_input(
    "Control Range",
    min_value=0,
    value=100
)

Battery_Type = st.selectbox(
    "Battery Type",
    [
        "Lithium Battery",
        "AA Battery",
        "AA Rechargeable Battery",
        "AA Alkaline Battery",
        "AAA Battery",
        "AAA Rechargeable Battery",
        "AAA Alkaline Battery"
    ]
)

Weight = st.number_input(
    "Weight",
    min_value=0,
    value=250
)

Price = st.number_input(
    "Price",
    min_value=0.0,
    value=2705.0
)

Actual_Price = st.number_input(
    "Actual Price",
    min_value=0.0,
    value=8999.0
)

Discount = st.number_input(
    "Discount (%)",
    min_value=0.0,
    max_value=100.0,
    value=50.0
)


# --------------------------------------------------
# Prediction
# --------------------------------------------------

if st.button("Predict Drone Type"):

    # Create input DataFrame

    input_data = pd.DataFrame({
        "Control Range": [Control_Range],
        "Battery Type": [Battery_Type],
        "Weight": [Weight],
        "Price": [Price],
        "Actual Price": [Actual_Price],
        "Discount (%)": [Discount]
    })


    # --------------------------------------------------
    # Apply One-Hot Encoding
    # --------------------------------------------------

    input_data = pd.get_dummies(
        input_data,
        columns=["Battery Type"],
        drop_first=True
    )


    # --------------------------------------------------
    # Match Training Feature Order
    # --------------------------------------------------

    input_data = input_data.reindex(
        columns=model.feature_names_in_,
        fill_value=0
    )


    # --------------------------------------------------
    # Make Prediction
    # --------------------------------------------------

    prediction = model.predict(input_data)[0]

    predicted_type = label_encoder.inverse_transform(
        [prediction]
    )[0]


    # --------------------------------------------------
    # Display Result
    # --------------------------------------------------

    st.success(
        f"🚁 {Name} is predicted as: {predicted_type}"
    )